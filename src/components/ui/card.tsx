import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & {
    variant?: "default" | "elevated" | "glass" | "outline";
  }
>(({ className, variant = "default", ...props }, ref) => {
  const variants = {
    default: "bg-card shadow-soft",
    elevated: "bg-card shadow-card",
    glass: "bg-card/80 backdrop-blur-sm shadow-soft",
    outline: "bg-background border-2 border-border",
  };

  return (
    <div
      ref={ref}
      className={cn(
        "rounded-2xl text-card-foreground transition-all duration-200",
        variants[variant],
        className
      )}
      {...props}
    />
  );
});
Card.displayName = "Card";

